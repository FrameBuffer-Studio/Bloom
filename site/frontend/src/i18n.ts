const MESSAGES: Readonly<Record<Language, Readonly<Record<MessageKey, string>>>> = { ru, en };

let language: Language = DEFAULT_LANGUAGE;

export function t(key: MessageKey, params: Readonly<Record<string, string | number>> = {}): string {
  return MESSAGES[language][key].replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

export function currentLanguage(): Language {
  return language;
}

export function setLanguage(next: Language): void {
  language = next;
  document.documentElement.lang = next;
  writeValue("language", next);
}

export function initialLanguage(): Language {
  const saved = readValue("language");
  if (isLanguage(saved)) {
    return saved;
  }
  const preferred = navigator.languages.map((tag) => tag.slice(0, 2).toLowerCase()).find(isLanguage);
  return preferred ?? DEFAULT_LANGUAGE;
}

export function languageName(target: Language): string {
  return t(target === "ru" ? "lang.ru" : "lang.en");
}

